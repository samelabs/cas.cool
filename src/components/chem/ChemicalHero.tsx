'use client'

import Link from 'next/link'
import { useEffect, useRef, useState } from 'react'
import { t } from '@/lib/i18n'
import { hgsChemicalUrl } from '@/lib/cas-format'

const VISIBLE_ALIASES = 3

/** Render a molecular formula with proper subscripts: C2H6O → C₂H₆O. */
function Formula({ value }: { value: string }) {
  const parts = value.split(/(\d+\.?\d*)/g).filter(Boolean)
  return (
    <>
      {parts.map((p, i) =>
        /^\d/.test(p) ? (
          <sub key={i} className="text-[0.7em]">
            {p}
          </sub>
        ) : (
          <span key={i}>{p}</span>
        ),
      )}
    </>
  )
}

/**
 * Full hero card for a CAS page — identity (name + CAS + badges), 2D
 * structure (static SVG generated offline by the server; its existence is
 * recorded in Chemical.structureSvgAt), core property grid (formula /
 * average mass / posts), and clickable alias list.
 *
 * The structure card renders ONLY when the DB says an SVG exists AND the
 * browser actually loaded it; any failure simply removes the card (no
 * placeholder, no spinner) and the property grid goes full-width.
 *
 * "Empty" CAS pages are NOT empty informationally: everything here renders
 * from the one-time stock import; only the post count can be zero.
 */
export function ChemicalHero({
  casNumber,
  names,
  banned,
  hcid,
  hasStructureSvg,
  molecularFormula,
  averageMass,
  postCount,
}: {
  casNumber: string
  names: string[]
  banned: boolean
  hcid: number | null
  hasStructureSvg: boolean
  molecularFormula: string | null
  averageMass: number | null
  postCount: number
}) {
  const [showAllAliases, setShowAllAliases] = useState(false)
  const [imgFailed, setImgFailed] = useState(false)
  const imgRef = useRef<HTMLImageElement>(null)

  // SSR-hydrated images that failed BEFORE hydration never fire React's
  // onError (no listener attached yet) — detect that case after mount.
  useEffect(() => {
    const el = imgRef.current
    if (el && el.complete && el.naturalWidth === 0) setImgFailed(true)
  }, [casNumber])
  const showStructure = hasStructureSvg && !imgFailed
  const primaryName = names[0] || null
  const aliases = names.slice(1)
  const shownAliases = showAllAliases ? aliases : aliases.slice(0, VISIBLE_ALIASES)
  const hiddenCount = aliases.length - shownAliases.length

  return (
    <section className="bg-gradient-to-b from-brand-tint/40 to-transparent px-4 pb-5 pt-3">
      {/* Identity row */}
      <div className="flex items-start justify-between gap-3">
        <div className="min-w-0">
          {primaryName ? (
            <>
              <h1 className="text-xl font-bold leading-snug text-ink">{primaryName}</h1>
              <p className="mt-0.5 font-mono text-sm text-ink-muted">CAS {casNumber}</p>
            </>
          ) : (
            <h1 className="font-mono text-xl font-bold text-brand-ink">CAS {casNumber}</h1>
          )}
          {banned && (
            <span className="mt-1.5 inline-flex items-center rounded-full bg-danger/10 px-2.5 py-0.5 text-xs font-semibold text-danger">
              {t.common.restricted}
            </span>
          )}
        </div>

        {/* HCID badge — external link to the HGS compound page */}
        {hcid != null && (
          <a
            href={hgsChemicalUrl(hcid)}
            target="_blank"
            rel="noopener noreferrer"
            title={t.cas.hgsBadgeTitle}
            className="inline-flex shrink-0 items-center gap-1 rounded-full bg-brand/10 px-2.5 py-0.5 font-mono text-xs font-semibold text-brand-ink transition-colors hover:bg-brand/20"
          >
            {t.cas.hcidBadge(hcid)}
            <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2} className="h-3 w-3" aria-hidden>
              <path d="M7 17L17 7M17 7H9m8 0v8" strokeLinecap="round" strokeLinejoin="round" />
            </svg>
          </a>
        )}
      </div>

      {/* Structure + property grid — two columns when the structure SVG
          exists, full-width property list otherwise (no placeholder) */}
      <div
        className={
          showStructure
            ? 'mt-4 grid gap-4 sm:grid-cols-[minmax(0,260px)_1fr] sm:items-stretch'
            : 'mt-4'
        }
      >
        {/* Structure card — static SVG pre-generated by the offline
            batch job (CAS-named files, existence tracked in DB).
            No spinner, no client-side chemistry; onerror removes it. */}
        {showStructure && (
          <div className="grid min-h-[200px] place-items-center overflow-hidden rounded-2xl bg-surface ring-1 ring-line">
            {/* eslint-disable-next-line @next/next/no-img-element -- plain static asset, not the image optimizer */}
            <img
              ref={imgRef}
              src={`/mol-svg/${casNumber}.svg`}
              alt={t.cas.structureAlt(primaryName || casNumber)}
              width={260}
              height={200}
              loading="lazy"
              decoding="async"
              onError={() => setImgFailed(true)}
              className="h-auto w-full max-w-[260px]"
            />
          </div>
        )}

        {/* Property list — semantic <dl>, one definition per row */}
        <dl className="flex flex-col justify-center gap-2.5 rounded-2xl bg-surface px-4 py-3.5 ring-1 ring-line">
          {molecularFormula && (
            <div className="flex items-baseline justify-between gap-3">
              <dt className="text-xs uppercase tracking-wide text-ink-faint">{t.cas.molecularFormulaLabel}</dt>
              <dd className="truncate font-mono text-sm font-medium text-ink">
                <Formula value={molecularFormula} />
              </dd>
            </div>
          )}
          {averageMass != null && (
            <div className="flex items-baseline justify-between gap-3">
              <dt className="text-xs uppercase tracking-wide text-ink-faint">{t.cas.averageMassLabelShort}</dt>
              <dd className="font-mono text-sm font-medium text-ink">{averageMass.toFixed(2)} g/mol</dd>
            </div>
          )}
          <div className="flex items-baseline justify-between gap-3">
            <dt className="text-xs uppercase tracking-wide text-ink-faint">{t.cas.discussionsLabel}</dt>
            <dd className="text-sm font-semibold text-ink">{t.common.postsCount(postCount)}</dd>
          </div>
          {hcid != null && (
            <div className="flex items-baseline justify-between gap-3">
              <dt className="text-xs uppercase tracking-wide text-ink-faint">HGS</dt>
              <dd>
                <a
                  href={hgsChemicalUrl(hcid)}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="text-sm font-medium text-brand transition-colors hover:text-brand-ink"
                >
                  {t.cas.viewOnHgs} →
                </a>
              </dd>
            </div>
          )}
        </dl>
      </div>

      {/* Aliases — clickable search links, collapsed beyond 3 */}
      {aliases.length > 0 && (
        <div className="mt-4">
          <p className="text-xs uppercase tracking-wide text-ink-faint">{t.cas.alsoKnownAs}</p>
          <div className="mt-1.5 flex flex-wrap gap-1.5">
            {shownAliases.map((n) => (
              <Link
                key={n}
                href={`/explore?q=${encodeURIComponent(n)}`}
                className="max-w-full truncate rounded-full bg-surface px-3 py-1 text-xs text-ink-muted ring-1 ring-line transition-colors hover:text-brand hover:ring-brand/30"
              >
                {n}
              </Link>
            ))}
            {hiddenCount > 0 && (
              <button
                type="button"
                onClick={() => setShowAllAliases(true)}
                className="rounded-full px-3 py-1 text-xs font-medium text-brand transition-colors hover:text-brand-ink"
              >
                +{hiddenCount}
              </button>
            )}
          </div>
        </div>
      )}
    </section>
  )
}
